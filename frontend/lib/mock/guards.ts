const generateAttendance = (basePattern: string[]): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const now = new Date("2026-08-27T12:00:00Z");
  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dayName = d.toISOString().split("T")[0];
    const pat = basePattern[i % basePattern.length];
    let status: "present" | "absent" | "late" | "leave" | "swap" = "present";
    let hours = 8;
    if (pat === "L") { status = "late"; hours = 7.5; }
    else if (pat === "A") { status = "absent"; hours = 0; }
    else if (pat === "V") { status = "leave"; hours = 0; }
    else if (pat === "S") { status = "swap"; hours = 8; }
    records.push({ date: dayName, status, hours });
  }
  return records;
};

